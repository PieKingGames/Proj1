# for loop
# syntax:

# for item in list_of_items:
#     do something to each item

# testing for loop
fruits = ["Apple", "Peach", "Pear"]
# the item is basically a temporary variable. think of it as a saying 'this is the fruit we're processing.'

for fruit in fruits: # whenever there is a colon, it means the next line is indented and part of the loop.
    print(fruit)
# it is assigning each string to 'fruit,' and then printing 'fruit.'
    print(fruit + " pie")
# now after printing the fruit, it prints fruit again but adds " pie" to it.

